package journal

import (
	"crypto/sha256"

	bolt "go.etcd.io/bbolt"
	"itom.local/core/pool"
	"itom.local/core/wire"
)

func (s *Store) grant(tx *bolt.Tx, ref GrantRef) (Grant, error) {
	if ref.Store != s.id || ref.ID == 0 {
		return Grant{}, ErrScope
	}
	raw := tx.Bucket(grantBucket).Get(key(ref.ID))
	if raw == nil {
		return Grant{}, ErrMissing
	}
	var g Grant
	if err := decode(raw, &g); err != nil {
		return Grant{}, err
	}
	if g.Ref != ref {
		return Grant{}, ErrScope
	}
	return g, nil
}
func (s *Store) attempt(tx *bolt.Tx, ref AttemptRef) (Attempt, Grant, error) {
	g, err := s.grant(tx, ref.Grant)
	if err != nil {
		return Attempt{}, Grant{}, err
	}
	if ref.ID == 0 {
		return Attempt{}, Grant{}, ErrScope
	}
	raw := tx.Bucket(attemptBucket).Get(key(ref.ID))
	if raw == nil {
		return Attempt{}, Grant{}, ErrMissing
	}
	var a Attempt
	if err = decode(raw, &a); err != nil {
		return Attempt{}, Grant{}, err
	}
	if a.Ref != ref {
		return Attempt{}, Grant{}, ErrScope
	}
	return a, g, nil
}
func next(tx *bolt.Tx, name, countName string, maximum int) (uint64, error) {
	m := tx.Bucket(metaBucket)
	count, err := number(m, countName)
	if err != nil {
		return 0, err
	}
	if count >= uint64(maximum) {
		return 0, ErrLimit
	}
	last, err := number(m, name)
	if err != nil {
		return 0, err
	}
	if last == ^uint64(0) {
		return 0, ErrLimit
	}
	if err = putNumber(m, name, last+1); err != nil {
		return 0, err
	}
	if err = putNumber(m, countName, count+1); err != nil {
		return 0, err
	}
	return last + 1, nil
}
func decrease(tx *bolt.Tx, name string) error {
	m := tx.Bucket(metaBucket)
	n, err := number(m, name)
	if err != nil {
		return err
	}
	if n == 0 {
		return ErrCorrupt
	}
	return putNumber(m, name, n-1)
}

// Issue reserves bytes and message slots against BOTH the shared account and
// its user's protected share in the same durable transaction. These are local
// writer grants, not network WRITE_GRANTs for a remote endpoint.
func (s *Store) Issue(scope Scope, limit pool.Amount) (Grant, error) {
	return s.issue(scope, limit, false)
}
func (s *Store) issue(scope Scope, limit pool.Amount, remote bool) (Grant, error) {
	var result Grant
	err := s.write(func(tx *bolt.Tx) error { return s.issueTx(tx, scope, limit, remote, &result) })
	if err != nil {
		return Grant{}, err
	}
	return result, nil
}

func (s *Store) issueTx(tx *bolt.Tx, scope Scope, limit pool.Amount, remote bool, result *Grant) error {
	if remote {
		if err := putNumber(tx.Bucket(metaBucket), "schema", schema); err != nil {
			return err
		}
	}
	a, u, e := s.owner(scope.Account, scope.User)
	if e != nil {
		return e
	}
	if scope.Session == (wire.ID{}) {
		return ErrScope
	}
	if !s.ready[ownerKey(scope.Account, scope.User)] {
		return ErrRecovery
	}
	if !validAmount(limit) {
		return ErrLimit
	}
	accountHeld, e := balance(tx, accountKey(scope.Account))
	if e != nil {
		return e
	}
	userHeld, e := balance(tx, ownerKey(scope.Account, scope.User))
	if e != nil {
		return e
	}
	if !within(accountHeld, a.Limit) || !within(userHeld, u.Limit) {
		return ErrCorrupt
	}
	if !within(limit, sub(a.Limit, accountHeld)) || !within(limit, sub(u.Limit, userHeld)) {
		return ErrLimit
	}
	if e = s.userCount(tx, scope.User, true, true); e != nil {
		return e
	}
	id, e := next(tx, "last_grant", "grant_count", s.config.MaxGrants)
	if e != nil {
		return e
	}
	*result = Grant{Ref: GrantRef{Store: s.id, ID: id, Scope: scope}, Run: s.run, Limit: limit, Remote: remote}
	if e = changeBalance(tx, scope, limit, false); e != nil {
		return e
	}
	return putJSON(tx.Bucket(grantBucket), id, result)
}

// Prepare charges one physical attempt (including any repair) and commits its
// ownership hash BEFORE Start can authorize I/O. Encoded size includes complete
// stored MIME bytes, not just DATA. Decoded bytes are hashed and never persisted.
// Batch must be freshly generated by the caller for EACH physical attempt.
func (s *Store) Prepare(ref GrantRef, folder string, batch wire.ID, encoded uint64, decoded []byte) (Attempt, error) {
	return s.prepare(ref, folder, batch, encoded, decoded, false)
}

// PrepareStarted durably charges and transfers one writer permission in one
// transaction. Only a successful return authorizes I/O. A lost commit reply
// retains a Started intent for recovery; it never permits retrying APPEND.
func (s *Store) PrepareStarted(ref GrantRef, folder string, batch wire.ID, encoded uint64, decoded []byte) (Attempt, error) {
	return s.prepare(ref, folder, batch, encoded, decoded, true)
}

func validAttemptBody(batch wire.ID, encoded uint64, decoded []byte) bool {
	return batch != (wire.ID{}) && len(decoded) > 0 && len(decoded) <= MaxDecoded && encoded >= uint64(len(decoded)) && encoded <= MaxEncoded
}

func (s *Store) prepare(ref GrantRef, folder string, batch wire.ID, encoded uint64, decoded []byte, started bool) (Attempt, error) {
	if !validAttemptBody(batch, encoded, decoded) {
		return Attempt{}, ErrLimit
	}
	digest := sha256.Sum256(decoded)
	var result Attempt
	err := s.write(func(tx *bolt.Tx) error {
		return s.prepareTx(tx, ref, folder, batch, encoded, uint64(len(decoded)), digest, started, &result)
	})
	if err != nil {
		return Attempt{}, err
	}
	return result, nil
}

func (s *Store) prepareTx(tx *bolt.Tx, ref GrantRef, folder string, batch wire.ID, encoded, decodedBytes uint64, digest [32]byte, started bool, result *Attempt) error {
	g, e := s.grant(tx, ref)
	if e != nil {
		return e
	}
	if g.Remote {
		return ErrScope
	}
	if g.Run != s.run {
		return ErrGeneration
	}
	if g.Closed {
		return ErrState
	}
	if !s.ready[ownerKey(ref.Scope.Account, ref.Scope.User)] {
		return ErrRecovery
	}
	if !s.ownsFolder(ref.Scope, folder) {
		return ErrScope
	}
	n := pool.Amount{Bytes: encoded, Messages: 1}
	if !within(g.Used, g.Limit) {
		return ErrCorrupt
	}
	if !within(n, sub(g.Limit, g.Used)) {
		return ErrLimit
	}
	if e = s.userCount(tx, ref.Scope.User, false, true); e != nil {
		return e
	}
	id, e := next(tx, "last_attempt", "attempt_count", s.config.MaxAttempts)
	if e != nil {
		return e
	}
	*result = Attempt{Ref: AttemptRef{Grant: ref, ID: id}, Run: s.run, Batch: batch, Folder: folder,
		EncodedBytes: encoded, DecodedBytes: decodedBytes, Digest: digest, State: Prepared}
	if started {
		result.State = Started
	}
	g.Used = add(g.Used, n)
	if e = putJSON(tx.Bucket(grantBucket), ref.ID, g); e != nil {
		return e
	}
	if e = putJSON(tx.Bucket(attemptBucket), id, result); e != nil {
		return e
	}
	return indexLocalAttempt(tx, *result)
}

// StartLocalAttempt combines exact local quota reservation, charged intent and
// single-writer permission in one durable transaction. Its one-message grant
// is closed immediately, but all physical exposure remains charged until proof.
// Intended for bodies whose bytes do not contain their own new grant identity.
func (s *Store) StartLocalAttempt(scope Scope, folder string, batch wire.ID, encoded uint64, decoded []byte) (Attempt, error) {
	if !validAttemptBody(batch, encoded, decoded) {
		return Attempt{}, ErrLimit
	}
	digest := sha256.Sum256(decoded)
	var result Attempt
	err := s.write(func(tx *bolt.Tx) error {
		var grant Grant
		if err := s.issueTx(tx, scope, pool.Amount{Bytes: encoded, Messages: 1}, false, &grant); err != nil {
			return err
		}
		if err := s.prepareTx(tx, grant.Ref, folder, batch, encoded, uint64(len(decoded)), digest, true, &result); err != nil {
			return err
		}
		return s.closeGrantTx(tx, grant.Ref)
	})
	if err != nil {
		return Attempt{}, err
	}
	return result, nil
}

// Start transfers permission to the single writer exactly ONCE. Only successful
// return authorizes APPEND. Repeating Start is an error, not a retry permit.
func (s *Store) Start(ref AttemptRef) (Attempt, error) {
	var result Attempt
	err := s.write(func(tx *bolt.Tx) error {
		a, g, e := s.attempt(tx, ref)
		if e != nil {
			return e
		}
		if g.Remote {
			return ErrScope
		}
		if a.Run != s.run {
			return ErrGeneration
		}
		if !s.ready[ownerKey(ref.Grant.Scope.Account, ref.Grant.Scope.User)] {
			return ErrRecovery
		}
		if a.State != Prepared {
			return ErrState
		}
		a.State = Started
		result = a
		return putJSON(tx.Bucket(attemptBucket), ref.ID, a)
	})
	if err != nil {
		return Attempt{}, err
	}
	return result, nil
}

type Result uint8

const (
	Accepted Result = iota
	Uncertain
	RejectedBeforeCommit
)

// Complete handles a current-run writer's outcome. A lost APPEND reply is
// Uncertain, never RejectedBeforeCommit. Rejection is legal only directly from
// Started, based on a definitive no-write result; absence in SEARCH is not one.
func (s *Store) Complete(ref AttemptRef, outcome Result) error {
	return s.write(func(tx *bolt.Tx) error { return s.completeTx(tx, ref, outcome) })
}

func (s *Store) completeTx(tx *bolt.Tx, ref AttemptRef, outcome Result) error {
	a, g, e := s.attempt(tx, ref)
	if e != nil {
		return e
	}
	if g.Remote {
		return ErrScope
	}
	if a.Run != s.run {
		return ErrGeneration
	}
	if a.State == Prepared || outcome > RejectedBeforeCommit {
		return ErrState
	}
	switch outcome {
	case RejectedBeforeCommit:
		if a.State != Started {
			return ErrState
		}
		return s.releaseAttempt(tx, a, g)
	case Uncertain:
		// A verified FETCH can precede the delayed APPEND reply.
		if a.State == Committed {
			return nil
		}
		a.State = Unknown
	case Accepted:
		a.State = Committed
	}
	return putJSON(tx.Bucket(attemptBucket), ref.ID, a)
}

// CompleteAndClose records the outcome and returns only unused local grant
// allocation atomically. Started/unknown physical exposure remains charged.
func (s *Store) CompleteAndClose(ref AttemptRef, outcome Result) error {
	return s.write(func(tx *bolt.Tx) error {
		_, g, err := s.attempt(tx, ref)
		if err != nil {
			return err
		}
		if err = s.completeTx(tx, ref, outcome); err != nil {
			return err
		}
		if g.Closed {
			return nil
		}
		return s.closeGrantTx(tx, ref.Grant)
	})
}
func (s *Store) CancelPrepared(ref AttemptRef) error {
	return s.write(func(tx *bolt.Tx) error {
		a, g, e := s.attempt(tx, ref)
		if e != nil {
			return e
		}
		if g.Remote {
			return ErrScope
		}
		if a.State != Prepared {
			return ErrState
		}
		return s.releaseAttempt(tx, a, g)
	})
}

// Observe proves ownership using content, account, exact folder and mailbox
// incarnation. Current-run inventory may reconcile old-run uncertain intents.
func (s *Store) Observe(ref AttemptRef, run uint64, evidence Observation) error {
	return s.ObserveMany(run, []ObservedAttempt{{Ref: ref, Observation: evidence}})
}

// ObserveMany binds fully decoded evidence in one durable transaction. Every
// proof is checked; any invalid member rolls back the entire batch. A physical
// locator can bind only one attempt in a batch, including identical digests.
func (s *Store) ObserveMany(run uint64, proofs []ObservedAttempt) error {
	if len(proofs) == 0 || len(proofs) > MaxProofBatch {
		return ErrLimit
	}
	digests := make([][32]byte, len(proofs))
	for i, proof := range proofs {
		if len(proof.Observation.Decoded) == 0 || len(proof.Observation.Decoded) > MaxDecoded {
			return ErrLimit
		}
		digests[i] = sha256.Sum256(proof.Observation.Decoded)
	}
	return s.write(func(tx *bolt.Tx) error { return s.observeManyTx(tx, run, proofs, digests) })
}

// observeManyTx preserves the same full proof validation for standalone scans
// and atomic remote registration/observation. The caller owns one transaction.
func (s *Store) observeManyTx(tx *bolt.Tx, run uint64, proofs []ObservedAttempt, digests [][32]byte) error {
	if len(proofs) == 0 || len(proofs) > MaxProofBatch || len(digests) != len(proofs) {
		return ErrLimit
	}

	if run != s.run {
		return ErrGeneration
	}
	type locator struct {
		account, folder string
		location        Location
	}
	seen := map[locator]bool{}
	refs := map[AttemptRef]bool{}
	for i, proof := range proofs {
		ref, evidence := proof.Ref, proof.Observation
		loc := locator{evidence.Account, evidence.Folder, evidence.Location}
		if seen[loc] || refs[ref] {
			return ErrScope
		}
		seen[loc], refs[ref] = true, true
		a, g, e := s.attempt(tx, ref)
		if e != nil {
			return e
		}
		if a.State == Prepared {
			return ErrState
		}
		if evidence.Account != ref.Grant.Scope.Account || evidence.Folder != a.Folder ||
			evidence.Location.UIDValidity == 0 || evidence.Location.UID == 0 ||
			uint64(len(evidence.Decoded)) != a.DecodedBytes || digests[i] != a.Digest {
			return ErrScope
		}
		if g.Remote && (evidence.EncodedBytes != a.EncodedBytes || !wire.CheckPhysical(evidence.Decoded, quotaKey(g), a.Ordinal, a.Batch)) {
			return ErrScope
		}
		if a.Location.UIDValidity == evidence.Location.UIDValidity && a.Location.UID != evidence.Location.UID {
			return ErrState
		}
		a.State, a.Location = Committed, evidence.Location
		if e = putJSON(tx.Bucket(attemptBucket), ref.ID, a); e != nil {
			return e
		}
	}
	return nil
}

// Deleted is a TRUSTED local IMAP-worker completion after verifying actual
// deletion/absence of this observed UID in the SAME current UIDVALIDITY. A
// \Deleted flag, RECEIPT, timeout, peer counter or marker cannot call this API.
func (s *Store) Deleted(ref AttemptRef, run uint64, location Location) error {
	return s.DeletedMany(run, []Deletion{{Ref: ref, Location: location}})
}

// DeletedMany refunds only validated observed locators, atomically and with
// fsync still enabled. A failed or lost commit acknowledgement poisons the
// store just like a single proof; callers cannot publish speculative refunds.
func (s *Store) DeletedMany(run uint64, proofs []Deletion) error {
	if len(proofs) == 0 || len(proofs) > MaxProofBatch {
		return ErrLimit
	}
	return s.write(func(tx *bolt.Tx) error {
		if run != s.run {
			return ErrGeneration
		}
		for _, proof := range proofs {
			ref, location := proof.Ref, proof.Location
			if s.localPublications[ref] {
				return ErrState
			}
			a, g, e := s.attempt(tx, ref)
			if e != nil {
				return e
			}
			if a.State != Committed || a.Location.UIDValidity == 0 || a.Location.UID == 0 || a.Location != location {
				return ErrScope
			}
			if e = s.releaseAttempt(tx, a, g); e != nil {
				return e
			}
		}
		return nil
	})
}

// AbsentFromCompleteInventory releases one LOCAL physical attempt only after the
// caller has completed a bounded full inventory of the attempt's exact folder
// and proved that the folder is empty. This is stronger evidence than a lost
// APPEND completion: regardless of whether that APPEND once committed, it no
// longer consumes mailbox storage. Remote attempts are never eligible.
//
// This recovery primitive exists so an administrator/provider-side deletion
// cannot leave conservative local physical debt permanently wedged at the
// admission limit after the mailbox is already empty.
func (s *Store) AbsentFromCompleteInventory(ref AttemptRef, run uint64, folder string) error {
	return s.write(func(tx *bolt.Tx) error {
		if s.localPublications[ref] {
			return ErrState
		}
		if run != s.run {
			return ErrGeneration
		}
		a, g, e := s.attempt(tx, ref)
		if e != nil {
			return e
		}
		if g.Remote || a.State == Prepared || folder == "" || a.Folder != folder {
			return ErrScope
		}
		return s.releaseAttempt(tx, a, g)
	})
}
func (s *Store) releaseAttempt(tx *bolt.Tx, a Attempt, g Grant) error {
	n := charge(a)
	if !within(g.Released, g.Used) || !within(n, sub(g.Used, g.Released)) {
		return ErrCorrupt
	}
	g.Released = add(g.Released, n)
	if err := changeBalance(tx, g.Ref.Scope, n, true); err != nil {
		return err
	}
	if a.Ordinal > 0 {
		if err := tx.Bucket(remoteIndexBucket).Delete(remoteIndexKey(g.Ref.ID, a.Ordinal)); err != nil {
			return err
		}
	} else if err := tx.Bucket(localIndexBucket).Delete(localIndexKey(a)); err != nil {
		return err
	}
	if err := tx.Bucket(attemptBucket).Delete(key(a.Ref.ID)); err != nil {
		return err
	}
	if err := decrease(tx, "attempt_count"); err != nil {
		return err
	}
	if err := s.userCount(tx, g.Ref.Scope.User, false, false); err != nil {
		return err
	}
	return s.saveGrant(tx, g)
}
func (s *Store) saveGrant(tx *bolt.Tx, g Grant) error {
	// Local-only probe journals stay compatible with schema2. Retained remote
	// final status requires schema3 so old binaries cannot silently delete it.
	if g.Remote {
		if err := putNumber(tx.Bucket(metaBucket), "schema", schema); err != nil {
			return err
		}
	}

	if !g.Remote && g.Closed && g.Used == g.Released {
		if err := tx.Bucket(grantBucket).Delete(key(g.Ref.ID)); err != nil {
			return err
		}
		if err := s.userCount(tx, g.Ref.Scope.User, true, false); err != nil {
			return err
		}
		return decrease(tx, "grant_count")
	}
	return putJSON(tx.Bucket(grantBucket), g.Ref.ID, g)
}

// CloseGrant returns ONLY unused local allocation, including after restart.
// Every potentially started writer already has a durable charged intent, so
// this does not free unresolved attempts. Never use it for a remote grant.
func (s *Store) CloseGrant(ref GrantRef) error {
	return s.write(func(tx *bolt.Tx) error { return s.closeGrantTx(tx, ref) })
}

func (s *Store) closeGrantTx(tx *bolt.Tx, ref GrantRef) error {
	g, e := s.grant(tx, ref)
	if e != nil {
		return e
	}
	if g.Remote {
		return ErrScope
	}
	if g.Closed {
		return nil
	}
	if !within(g.Used, g.Limit) {
		return ErrCorrupt
	}
	if e = changeBalance(tx, ref.Scope, sub(g.Limit, g.Used), true); e != nil {
		return e
	}
	g.Closed = true
	return s.saveGrant(tx, g)
}
func (s *Store) GetAttempt(ref AttemptRef) (Attempt, error) {
	var a Attempt
	err := s.read(func(tx *bolt.Tx) error { var e error; a, _, e = s.attempt(tx, ref); return e })
	if err != nil {
		return Attempt{}, err
	}
	return a, nil
}
func (s *Store) GetGrant(ref GrantRef) (Grant, error) {
	var g Grant
	err := s.read(func(tx *bolt.Tx) error { var e error; g, e = s.grant(tx, ref); return e })
	if err != nil {
		return Grant{}, err
	}
	return g, nil
}

// ScanAttempts returns owned copies, at most 256. Cursor is the last returned
// ID, exclusive; finished entries can be removed between pages. IDs never recur.
func (s *Store) ScanAttempts(after uint64, limit int) ([]Attempt, error) {
	if limit < 1 || limit > 256 {
		return nil, ErrLimit
	}
	out := make([]Attempt, 0, limit)
	err := s.read(func(tx *bolt.Tx) error {
		if after == ^uint64(0) {
			return nil
		}
		c := tx.Bucket(attemptBucket).Cursor()
		for k, v := c.Seek(key(after + 1)); k != nil && len(out) < limit; k, v = c.Next() {
			var a Attempt
			if e := decode(v, &a); e != nil {
				return e
			}
			out = append(out, a)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	return out, nil
}
func (s *Store) ScanGrants(after uint64, limit int) ([]Grant, error) {
	if limit < 1 || limit > 256 {
		return nil, ErrLimit
	}
	out := make([]Grant, 0, limit)
	err := s.read(func(tx *bolt.Tx) error {
		if after == ^uint64(0) {
			return nil
		}
		c := tx.Bucket(grantBucket).Cursor()
		for k, v := c.Seek(key(after + 1)); k != nil && len(out) < limit; k, v = c.Next() {
			var g Grant
			if e := decode(v, &g); e != nil {
				return e
			}
			out = append(out, g)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	return out, nil
}
